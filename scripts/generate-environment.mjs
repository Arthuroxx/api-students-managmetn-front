// Generates `src/environments/environment.production.ts` before a production build.
//
// The file is Git-ignored: the build environment is the source of truth, not the
// repository. Precedence is process environment, then a local `.env` file, then an
// empty base URL (same origin). See docs/configuration.md.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputFile = resolve(projectRoot, 'src/environments/environment.production.ts');

/**
 * Normalizes and validates a raw `API_BASE_URL` value.
 *
 * Empty values are valid and mean "same origin". Non-empty values must be an
 * absolute `http(s)` origin; a trailing slash is removed. Returns the normalized
 * value and an error message, or `null` when the value is valid.
 */
export function normalizeApiBaseUrl(rawValue) {
  const apiBaseUrl = String(rawValue ?? '')
    .trim()
    .replace(/\/+$/, '');

  if (apiBaseUrl === '') {
    return { apiBaseUrl, error: null };
  }

  let parsed;
  try {
    parsed = new URL(apiBaseUrl);
  } catch {
    return {
      apiBaseUrl,
      error: `Invalid API_BASE_URL: "${rawValue}". Provide an http(s) origin or leave it empty.`,
    };
  }

  if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') {
    return {
      apiBaseUrl,
      error: `Invalid API_BASE_URL protocol: "${parsed.protocol}". Use http or https.`,
    };
  }

  return { apiBaseUrl, error: null };
}

/**
 * Renders the production environment module for a validated base URL.
 *
 * The value is serialized with `JSON.stringify`, so quotes, backslashes, newlines,
 * and other special characters are escaped instead of breaking the generated file
 * or injecting code into it.
 */
export function renderEnvironmentFile(apiBaseUrl) {
  return `import type { Environment } from './environment.model';

/**
 * Production configuration, generated by \`scripts/generate-environment.mjs\`.
 * Do not edit or commit this file: it is written on every production build from
 * the \`API_BASE_URL\` build-time variable. See docs/configuration.md.
 */
export const environment: Environment = {
  production: true,
  apiBaseUrl: ${JSON.stringify(apiBaseUrl)},
};
`;
}

/** Reads a single `KEY=value` pair from a `.env` file, if present. */
function readDotEnv(name) {
  const envFile = resolve(projectRoot, '.env');
  if (!existsSync(envFile)) {
    return undefined;
  }

  for (const line of readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
    if (match && match[1] === name) {
      return match[2].replace(/^(['"])(.*)\1$/, '$2');
    }
  }

  return undefined;
}

function main() {
  const rawValue = process.env.API_BASE_URL ?? readDotEnv('API_BASE_URL') ?? '';
  const { apiBaseUrl, error } = normalizeApiBaseUrl(rawValue);

  if (error) {
    console.error(error);
    process.exit(1);
  }

  writeFileSync(outputFile, renderEnvironmentFile(apiBaseUrl), 'utf8');
  console.log(
    `Generated src/environments/environment.production.ts (apiBaseUrl: ${JSON.stringify(apiBaseUrl)}).`,
  );
}

// Run only when invoked as a script, so the module stays importable from tests.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
